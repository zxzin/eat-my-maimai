import fs from 'node:fs/promises';
import { PACKS } from '../src/ingredient-rules.js';
import { buildLiveLoadout } from '../src/mcp-loadout.js';
import { normalizeStores, normalizeMenu, matchPackPrices, enrichMenuIdentities, buildShanghaiStoreSearch, buildPickupMenuArguments } from '../src/mcp-menu.js';
import { sanitizePublicSnapshot } from './build-single-html.mjs';

// The running local bridge already owns authentication. This command receives
// public product data only and never accepts or persists a credential.
const origin = 'http://127.0.0.1:5178';
async function call(path, body) {
  const response = await fetch(`${origin}/api/mcp/${path}`, {
    method: body ? 'POST' : 'GET', headers: { Origin: origin, ...(body ? { 'Content-Type': 'application/json' } : {}) },
    ...(body ? { body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(60000),
  });
  const data = await response.json();
  if (!response.ok) throw new Error(data.error?.message || '本机 MCP 查询失败。');
  return data;
}
const status = await call('status');
if (status.state !== 'connected') throw new Error('请先在本机游戏面板连接 MCP，再生成公开快照。');
const nutritionResponse = await call('nutrition', { arguments: {} });
const nutrition = buildLiveLoadout(nutritionResponse.result, PACKS, nutritionResponse.retrievedAt);
const stores = normalizeStores(await call('call', { name: 'query-nearby-stores', arguments: buildShanghaiStoreSearch(process.argv[2] || '人民广场') }));
const store = stores.find(item => item.businessStatus !== false);
if (!store) throw new Error('未找到可查询的上海参考门店，保留现有公开快照。');
const menuResponse = await call('call', { name: 'query-meals', arguments: buildPickupMenuArguments(store) });
const { menu } = await enrichMenuIdentities(normalizeMenu(menuResponse, { store }), PACKS, {
  loadDetail: code => call('call', { name: 'query-meal-detail', arguments: { ...buildPickupMenuArguments(store), code } }),
});
const { matched } = matchPackPrices(menu, PACKS);
if (!matched.length || !matched.some(item => Number.isFinite(item.publicPriceYuan))) throw new Error('门店菜单未匹配有效公开价格，保留现有公开快照。');
const snapshot = sanitizePublicSnapshot({
  retrievedAt: menu.retrievedAt, store: { code: store.code, name: store.name, city: '上海市', address: store.address },
  nutrition: { retrievedAt: nutrition.retrievedAt, foodCount: nutrition.foodCount, matchedIds: nutrition.matched.map(item => item.id) },
  products: matched,
});
const root = new URL('../', import.meta.url), json = JSON.stringify(snapshot, null, 2) + '\n';
await fs.mkdir(new URL('public/', root), { recursive: true });
await fs.writeFile(new URL('public/menu-snapshot.json', root), json);
await fs.writeFile(new URL('src/public-menu-snapshot.js', root), `// Generated by npm run sync:public. Public menu fields only.\nexport default ${json.trim()};\n`);
console.log(JSON.stringify({ file: 'public/menu-snapshot.json', store: snapshot.store.name, retrievedAt: snapshot.retrievedAt, nutritionCount: snapshot.nutrition.foodCount, products: snapshot.products.map(({ name, publicPriceYuan }) => ({ name, publicPriceYuan })) }, null, 2));
